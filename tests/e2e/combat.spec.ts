import { expect, test } from '@playwright/test'
import { advance, startGame, state } from './game-fixture.js'

test('fires and renders one front projectile through the real keyboard control', async ({ page }) => {
  await startGame(page)
  const canvas = page.locator('canvas')
  const before = await canvas.screenshot()
  await page.keyboard.down('Space')
  await advance(page, 100)
  await page.keyboard.up('Space')
  const fired = await state(page)
  expect(fired.projectiles).toHaveLength(1)
  expect(fired.projectiles[0]).toMatchObject({ weapon: 'frontFire', heading: 0, damage: 20, speed: 400 })
  expect(fired.projectiles[0].x).toBeCloseTo(236)
  expect(fired.effects.some(({ kind }) => kind === 'fire')).toBe(true)
  expect((await canvas.screenshot()).equals(before)).toBe(false)
})

test('fires parallel broadsides and respects independent held-fire cooldowns', async ({ page }) => {
  await startGame(page)
  for (const key of ['Space', 'q', 'e']) await page.keyboard.down(key)
  await advance(page, 350)
  let fired = await state(page)
  expect(fired.projectiles.filter(({ weapon }) => weapon === 'frontFire')).toHaveLength(1)
  for (const weapon of ['leftFire', 'rightFire']) {
    const side = fired.projectiles.filter((projectile) => projectile.weapon === weapon)
    expect(side).toHaveLength(3)
    expect(side.map(({ x }) => x)).toEqual([134, 150, 166])
    expect(new Set(side.map(({ heading }) => heading)).size).toBe(1)
    expect(side[0].heading).toBeCloseTo(weapon === 'leftFire' ? -Math.PI / 2 : Math.PI / 2)
  }
  await advance(page, 1000 / 60)
  fired = await state(page)
  expect(fired.projectiles.filter(({ weapon }) => weapon === 'frontFire')).toHaveLength(2)
  expect(fired.cooldowns).toEqual({ frontFire: 700, leftFire: 1000, rightFire: 1000 })
  await advance(page, 650)
  expect((await state(page)).cooldowns.leftFire).toBeCloseTo(2000)
  expect((await state(page)).cooldowns.rightFire).toBeCloseTo(2000)
  for (const key of ['Space', 'q', 'e']) await page.keyboard.up(key)
})

