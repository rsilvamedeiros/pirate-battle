test('freezes projectiles and cooldowns on pause without replaying held fire', async ({ page }) => {
  await startGame(page)
  await page.keyboard.down('Space')
  await advance(page, 50)
  await page.getByRole('button', { name: 'Pause', exact: true }).click()
  const paused = await state(page)
  await advance(page, 10000)
  expect(await state(page)).toEqual(paused)
  await page.getByRole('button', { name: 'Resume' }).click()
  await page.keyboard.down('Space')
  await advance(page, 350)
  expect((await state(page)).cooldowns).toEqual(paused.cooldowns)
  await page.keyboard.up('Space')
  await page.keyboard.down('Space')
  await advance(page, 1000 / 60)
  await page.keyboard.up('Space')
  expect((await state(page)).cooldowns.frontFire).toBeCloseTo(750)
})

test('moves and fires with simultaneous touch contacts and releases on cancellation', async ({ page }) => {
  await startGame(page)
  const controls = ['Forward', 'Front Fire', 'Left Fire', 'Right Fire']
  const points = await Promise.all(controls.map(async (name, id) => {
    const bounds = (await page.getByRole('button', { name, exact: true }).boundingBox())!
    return { id, x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 }
  }))
  const protocol = await page.context().newCDPSession(page)
  await protocol.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: points })
  await advance(page, 100)
  const fired = await state(page)
  expect(fired.player.x).toBeCloseTo(168)
  expect(fired.projectiles).toHaveLength(7)
  await protocol.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] })
  await advance(page, 400)
  const released = await state(page)
  expect(released.player).toEqual(fired.player)
  expect(released.cooldowns).toEqual(fired.cooldowns)
  await protocol.detach()
})

test('stops weapons at completion and clears them on restart', async ({ page }) => {
  await startGame(page)
  await advance(page, 119950)
  await page.keyboard.down('q')
  await advance(page, 50)
  await expect(page.getByRole('heading', { name: 'Voyage complete' })).toBeVisible()
  const completed = await state(page)
  await advance(page, 5000)
  expect(await state(page)).toEqual(completed)
  await page.keyboard.up('q')
  await page.getByRole('button', { name: 'Play Again', exact: true }).click()
  await expect.poll(() => page.evaluate(() => window.__game?.getState().status)).toBe('running')
  expect((await state(page)).projectiles).toHaveLength(0)
  expect((await state(page)).effects).toHaveLength(0)
  expect((await state(page)).cooldowns).toEqual({ frontFire: 0, leftFire: 0, rightFire: 0 })
})
